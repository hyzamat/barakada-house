"""Export the wok-toss clip as full-screen image sequences for the scroll-to-toss section.

Writes site/media/seq/l-###.webp (1280x720), p-###.webp (608x1080 centre crop)
and site/assets/js/toss-data.js.
"""
import glob, os, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
from build_media import resolve  # noqa: E402
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

OUT = os.path.join(ROOT, "site/media/seq")
JS = os.path.join(ROOT, "site/assets/js/toss-data.js")
FPS = 12

os.makedirs(OUT, exist_ok=True)
for f in glob.glob(os.path.join(OUT, "*.webp")):
    os.remove(f)
src = resolve("Chopsoy", "Wok_tossing_vegetables_and_chicken")
graph = f"fps={FPS},split=2[a][b];[a]scale=1280:720[l];[b]crop=608:1080:(iw-608)/2:0[p]"
r = subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", src, "-filter_complex", graph,
                    "-map", "[l]", "-c:v", "libwebp", "-quality", "54", os.path.join(OUT, "l-%03d.webp"),
                    "-map", "[p]", "-c:v", "libwebp", "-quality", "58", os.path.join(OUT, "p-%03d.webp")],
                   capture_output=True, text=True)
if r.returncode:
    sys.exit(r.stderr[-1500:])
n = len(glob.glob(os.path.join(OUT, "l-*.webp")))
with open(JS, "w", encoding="utf-8") as f:
    f.write("// Generated by build_toss.py: wok-toss scroll sequence.\n")
    f.write(f"export const TOSS = {{ frames: {n}, fps: {FPS} }};\n")
print("frames", n)
