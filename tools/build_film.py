"""Cut the hero scroll-film from the source clips and export it as image sequences.

Outputs site/media/film/l-###.webp (1280x720) and p-###.webp (608x1080 centre crop),
plus site/assets/js/film.js with frame count, fps and chapter ranges.
"""
import glob, json, os, subprocess, sys
sys.path.insert(0, os.path.dirname(__file__))
from build_media import DISHES, resolve  # noqa: E402
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

OUT = os.path.join(ROOT, "site/media/film")
JS = os.path.join(ROOT, "site/assets/js/film.js")
FPS = 10
T = 0.4  # dissolve length between chapters

# (clip id, start, end, label, line)
CHAPTERS = [
    ("inasal-04", 0.2, 2.9, "Uling", "It starts with fire."),
    ("inasal-06", 0.9, 3.6, "Inihaw", "Basted by hand over white-hot coals."),
    ("crispy-pata-06", 2.2, 4.9, "Crispy pata", "Crackling you can hear."),
    ("kare-kare-06", 0.0, 2.4, "Kare-kare", "Sauces that take their time."),
    ("kaldereta-05", 5.4, 8.6, "Kaldereta", "And yes, the cheese pull."),
    ("bulalo-10", 0.9, 3.6, "Bulalo", "Broths simmered all day."),
    ("chopsuey-04", 0.2, 2.9, "Chop suey", "Wok hei, every single order."),
    ("bulalo-12", 2.4, 6.4, "Salo-salo", "Made for the whole barkada."),
]


def source(cid):
    dish, n = cid.rsplit("-", 1)
    folder, steps = DISHES[dish]
    return resolve(folder, steps[int(n) - 1][0])


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in glob.glob(os.path.join(OUT, "*.webp")):
        os.remove(f)

    cmd = ["ffmpeg", "-v", "error", "-y"]
    for cid, a, b, *_ in CHAPTERS:
        cmd += ["-ss", str(a), "-t", str(b - a), "-i", source(cid)]

    parts, chain = [], []
    for i in range(len(CHAPTERS)):
        parts.append(f"[{i}:v]fps=24,scale=1920:1080,setsar=1,format=yuv420p,setpts=PTS-STARTPTS[c{i}]")
    length = CHAPTERS[0][2] - CHAPTERS[0][1]
    starts = [0.0]
    prev = "c0"
    for i in range(1, len(CHAPTERS)):
        offset = length - T
        out = f"x{i}"
        chain.append(f"[{prev}][c{i}]xfade=transition=fade:duration={T}:offset={offset:.3f}[{out}]")
        starts.append(offset + T / 2)
        length = offset + (CHAPTERS[i][2] - CHAPTERS[i][1])
        prev = out
    graph = ";".join(parts + chain + [
        f"[{prev}]fps={FPS},split=2[fa][fb]",
        "[fa]scale=1280:720[l]",
        "[fb]crop=608:1080:(iw-608)/2:0[p]",
    ])
    cmd += ["-filter_complex", graph,
            "-map", "[l]", "-c:v", "libwebp", "-quality", "54", "-fps_mode", "passthrough", os.path.join(OUT, "l-%03d.webp"),
            "-map", "[p]", "-c:v", "libwebp", "-quality", "58", "-fps_mode", "passthrough", os.path.join(OUT, "p-%03d.webp")]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(r.stderr[-2000:])

    frames = len(glob.glob(os.path.join(OUT, "l-*.webp")))
    chapters = []
    for i, (cid, a, b, label, line) in enumerate(CHAPTERS):
        end = starts[i + 1] if i + 1 < len(starts) else length
        chapters.append({"label": label, "line": line, "from": round(starts[i] * FPS), "to": min(frames - 1, round(end * FPS))})
    with open(JS, "w", encoding="utf-8") as f:
        f.write("// Generated by build_film.py: hero scroll-film frames and chapters.\n")
        f.write(f"export const FILM = {json.dumps({'frames': frames, 'fps': FPS, 'chapters': chapters}, indent=2)};\n")
    print("frames", frames, "length", round(length, 2), "s")


if __name__ == "__main__":
    main()
